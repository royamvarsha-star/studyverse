// Helper renderer for character face based on traits
export const CharacterFaceSvg: React.FC<{ character: GuessPersonCharacter; className?: string }> = ({
  character,
  className = 'w-16 h-16',
}) => {
  const skinColors: Record<string, string> = {
    fair: '#fff1f2',
    peach: '#fed7aa',
    tan: '#fdba74',
    warm: '#fcd34d',
  };

  const hairColors: Record<string, string> = {
    blonde: '#fde047',
    brown: '#78350f',
    pink: '#f472b6',
    black: '#18181b',
    cyan: '#06b6d4',
    purple: '#a855f7',
  };

  const eyeColors: Record<string, string> = {
    blue: '#0284c7',
    brown: '#713f12',
    green: '#16a34a',
    pink: '#ec4899',
  };

  const shirtColors: Record<string, string> = {
    pink: '#f472b6',
    blue: '#38bdf8',
    purple: '#c084fc',
    green: '#4ade80',
    yellow: '#fde047',
    black: '#334155',
  };

  const skin = skinColors[character.skinTone] || '#fed7aa';
  const hair = hairColors[character.hairColor] || '#78350f';
  const eye = eyeColors[character.eyeColor] || '#0284c7';
  const shirt = shirtColors[character.clothingColor] || '#38bdf8';

  return (
    <div className={`pixel-art inline-block ${className}`}>
      <svg viewBox="0 0 32 32" className="w-full h-full drop-shadow">
        {/* Hair Back */}
        <rect x="7" y="6" width="18" height="15" fill={hair} rx="2" />
        {/* Face */}
        <rect x="9" y="8" width="14" height="12" fill={skin} rx="2" />
        {/* Hair Bangs */}
        <rect x="8" y="5" width="16" height="5" fill={hair} />
        {character.hairColor === 'pink' || character.hairColor === 'purple' ? (
          <>
            <rect x="8" y="9" width="3" height="7" fill={hair} />
            <rect x="21" y="9" width="3" height="7" fill={hair} />
          </>
        ) : (
          <>
            <rect x="8" y="9" width="2" height="4" fill={hair} />
            <rect x="22" y="9" width="2" height="4" fill={hair} />
          </>
        )}

        {/* Hat if applicable */}
        {character.hasHat && (
          <g>
            <rect x="6" y="3" width="20" height="4" fill="#3b82f6" rx="1" />
            <rect x="4" y="6" width="24" height="2" fill="#1d4ed8" />
          </g>
        )}

        {/* Eyes */}
        <rect x="11" y="11" width="3" height="3" fill={eye} />
        <rect x="18" y="11" width="3" height="3" fill={eye} />
        <rect x="12" y="11" width="1" height="1" fill="#ffffff" />
        <rect x="19" y="11" width="1" height="1" fill="#ffffff" />

        {/* Glasses */}
        {character.hasGlasses && (
          <g>
            <rect x="10" y="10" width="5" height="5" fill="none" stroke="#0f172a" strokeWidth="1" />
            <rect x="17" y="10" width="5" height="5" fill="none" stroke="#0f172a" strokeWidth="1" />
            <line x1="15" y1="12" x2="17" y2="12" stroke="#0f172a" strokeWidth="1" />
          </g>
        )}

        {/* Blush */}
        {character.hasBlush && (
          <>
            <rect x="9" y="14" width="2" height="1" fill="#f87171" />
            <rect x="21" y="14" width="2" height="1" fill="#f87171" />
          </>
        )}

        {/* Earrings */}
        {character.hasEarrings && (
          <>
            <circle cx="8" cy="14" r="1" fill="#fde047" />
            <circle cx="24" cy="14" r="1" fill="#fde047" />
          </>
        )}

        {/* Mouth */}
        <rect x="14" y="16" width="4" height="1" fill="#be123c" />

        {/* Shirt & Body */}
        <rect x="8" y="20" width="16" height="10" fill={shirt} rx="2" />
        <polygon points="13,20 19,20 16,23" fill={skin} />
      </svg>
    </div>
  );
};
